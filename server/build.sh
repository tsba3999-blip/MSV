#!/usr/bin/env bash
# ============================================================
#  МСВ — сжатие кода перед выкладкой (необязательно)
#
#  Сжимает JS и CSS в /opt/msv/web: убирает пробелы, комментарии,
#  переименовывает внутренние переменные. Читать такой код тяжело,
#  копировать — ровно так же легко. Это препятствие для беглого
#  просмотра, не защита.
#
#  Запуск: bash build.sh   (после deploy.sh; требует интернет для npx)
#  Исходники в git не трогаются — сжимаются только копии в /opt/msv/web.
# ============================================================
set -euo pipefail
WEB="/opt/msv/web"
[ -d "$WEB" ] || { echo "нет $WEB — сначала deploy.sh"; exit 1; }
cd "$WEB"
echo "==> JS"
for f in *.js; do
  npx --yes terser "$f" --compress --mangle --output "$f.min" && mv "$f.min" "$f" && echo "    $f"
done
echo "==> CSS"
for f in *.css; do
  npx --yes csso "$f" --output "$f.min" && mv "$f.min" "$f" && echo "    $f"
done
echo "готово. Комментарии и отступы убраны; логика не изменилась."
